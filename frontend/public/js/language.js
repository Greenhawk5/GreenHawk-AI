function apply(lang) {
  const l = dict[lang] ? lang : "en";
  document.documentElement.setAttribute("lang", l);
  document.documentElement.setAttribute("dir", l === "fa" ? "rtl" : "ltr");

  const root = document.documentElement.style;
  root.setProperty("--pipe-status-idle", `"${dict[l]["pipeline.status.idle"]}"`);
  root.setProperty("--pipe-status-processing", `"${dict[l]["pipeline.status.processing"]}"`);
  root.setProperty("--pipe-status-complete", `"${dict[l]["pipeline.status.complete"]}"`);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[l][key] != null) el.textContent = dict[l][key];
  });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const raw = el.getAttribute("data-i18n-attr");
    raw.split(";").forEach((pair) => {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key && dict[l][key] != null) el.setAttribute(attr, dict[l][key]);
    });
  });

  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    const flag = dict[l]["nav.lang.toggle.flag"];
    const code = dict[l]["nav.lang.toggle.code"];
    if (flag && code) {
      btn.innerHTML = `<span class="lang-flag"><img src="${flag}" alt="Language flag" width="20" height="14"></span><span class="lang-code">${code}</span>`;
      btn.setAttribute("title", dict[l]["nav.lang.toggle"] || "");
    } else {
      btn.textContent = dict[l]["nav.lang.toggle"];
    }
  });

  const pipeBadge = document.getElementById("pipe-badge");
  if (pipeBadge) {
    const status = pipeBadge.getAttribute("data-status");
    const label = pipeBadge.querySelector("[data-label]");
    if (status && label && dict[l][`pipeline.status.${status}`] != null) {
      label.textContent = dict[l][`pipeline.status.${status}`];
    }
  }

  document.dispatchEvent(new CustomEvent("greenhawk:langchange", { detail: { lang: l } }));
}

export function initLanguage() {
  const stored = localStorage.getItem(KEY);
  const preferred = stored || (navigator.language && navigator.language.startsWith("fa") ? "fa" : "en");
  apply(preferred);
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const next = document.documentElement.getAttribute("lang") === "fa" ? "en" : "fa";
      localStorage.setItem(KEY, next);
      apply(next);
    });
  });
}

export function t(key) {
  const l = document.documentElement.getAttribute("lang") || "en";
  return (dict[l] && dict[l][key]) || (dict.en[key] ?? key);
}
